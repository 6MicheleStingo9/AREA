"""
Side-by-side comparison of the causal classifiers on the two test sets.

Collects the results files in evaluation/results/ (`causal_clf__*.json` for the MIT eval split,
`area_testset__*.json` for the AREA risks): every run of every model, with accuracy and macro-F1
per axis, the F1 of the `other` class and, for the models that return probabilities, the
expected calibration error. On the AREA risks it also splits macro-F1 by language. Writes
evaluation/results/comparison.md.

Usage (from the project root):
    python -m evaluation.compare
"""

import json
from pathlib import Path
from typing import Any, Dict, List, Tuple

AXES = ("entity", "intent", "timing")
RESULTS = Path(__file__).resolve().parent / "results"
TEST_SETS = {"causal_clf": "MIT eval split", "area_testset": "AREA risks"}
NAMES = {"pipeline": "gemini-2.5-flash, AREA pipeline labels"}


def _order(path: Path) -> Tuple[int, int, str]:
    """Gemini first, then Laya zero-shot, then the fine-tuned Laya runs."""
    slug = path.stem.split("__")[1]
    return (slug.startswith("laya"), "zeroshot" not in slug, slug)


def _runs(path: Path, res: Dict[str, Any]) -> List[Tuple[str, Dict[str, Any], Dict[str, Any]]]:
    """(label, metrics, subsets) for each run in a results file; the label is the file's model slug."""
    slug = path.stem.split("__")[1]
    slug = NAMES.get(slug, slug)
    if "runs" in res:
        return [(f"{slug}, run {i}", run["metrics"], {}) for i, run in enumerate(res["runs"], 1)]
    return [(slug, res["metrics"], res.get("subsets") or {})]


def _table(task: str, files: List[Path]) -> List[str]:
    pct = lambda v: f"{v * 100:.1f}"
    loaded = [(p, json.loads(p.read_text(encoding="utf-8"))) for p in files]
    rows = [run for p, res in loaded for run in _runs(p, res)]
    first = loaded[0][1]
    n = first["data"]["rows"]
    majority = first["majority_reference"]
    lines = [
        f"## {TEST_SETS[task]} ({n} risks)",
        "",
        "| Model | entity | intent | timing | F1 `other` | ECE |",
        "|---|---|---|---|---|---|",
        "| majority class (MIT train) | "
        + " | ".join(f"{pct(majority[ax]['accuracy'])} / {pct(majority[ax]['macro_f1'])}" for ax in AXES)
        + " | – | – |",
    ]
    for label, m, _ in rows:
        cells = " | ".join(f"{pct(m[ax]['accuracy'])} / {pct(m[ax]['macro_f1'])}" for ax in AXES)
        other = " / ".join(pct(m[ax]["per_class"]["other"]["f1"]) for ax in AXES)
        ece = " / ".join(pct(m[ax]["calibration"]["ece"]) for ax in AXES) if "calibration" in m["entity"] else "–"
        lines.append(f"| {label} | {cells} | {other} | {ece} |")
    if any(subsets for _, _, subsets in rows):
        lines += ["", "Macro-F1 % by language (EN / IT):", "", "| Model | entity | intent | timing |", "|---|---|---|---|"]
        for label, _, subsets in rows:
            if "language=en" in subsets and "language=it" in subsets:
                en, it = subsets["language=en"], subsets["language=it"]
                lines.append(f"| {label} | " + " | ".join(f"{pct(en[ax]['macro_f1'])} / {pct(it[ax]['macro_f1'])}" for ax in AXES) + " |")
    return lines + [""]


def main() -> None:
    lines = [
        "# Causal classifiers compared",
        "",
        "Accuracy / macro-F1 % per axis; F1 % of the `other` class and expected calibration error % "
        "(entity / intent / timing), the latter only for models that return probabilities. "
        "Generated by `python -m evaluation.compare` from the results files in this folder.",
        "",
    ]
    for task in TEST_SETS:
        files = sorted((p for p in RESULTS.glob(f"{task}__*.json") if "__limit" not in p.stem), key=_order)
        if files:
            lines += _table(task, files)
    (RESULTS / "comparison.md").write_text("\n".join(lines), encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
